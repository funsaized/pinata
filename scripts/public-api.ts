import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const entries = [
  { entry: "engine/index.ts", bridge: "engine/public.mjs", loader: "./typescript.mjs" },
  {
    entry: "engine/contracts/public.ts",
    bridge: "engine/contracts/public.mjs",
    loader: "../typescript.mjs",
  },
  {
    entry: "engine/runtime/index.ts",
    bridge: "engine/runtime/public.mjs",
    loader: "../typescript.mjs",
  },
  { entry: "engine/host/index.ts", bridge: "engine/host/public.mjs", loader: "../typescript.mjs" },
  {
    entry: "engine/sources/runtime.ts",
    bridge: "engine/sources/public.mjs",
    loader: "../typescript.mjs",
  },
] as const;

export async function publicApiFiles(): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  for (const item of entries) {
    const imported: Record<string, unknown> = await import(
      new URL(`../${item.entry}`, import.meta.url).href
    );
    const names = Object.keys(imported).sort();
    if (names.some((name) => !/^[A-Za-z_$][\w$]*$/.test(name) || name === "default"))
      throw new Error(`Public entry ${item.entry} has an unsupported export name`);
    const target = item.entry.slice(item.entry.lastIndexOf("/") + 1);
    files.set(
      item.bridge,
      [
        "// Generated by scripts/public-api.ts. Keep runtime bridges aligned with typed exports.",
        `import ${JSON.stringify(item.loader)};`,
        "",
        "// Node does not natively strip TypeScript inside node_modules. Install the",
        "// package-scoped loader before loading this entry's TypeScript module graph.",
        `const api = await import(${JSON.stringify(`./${target}`)});`,
        ...names.map((name) => `export const ${name} = api.${name};`),
        "",
      ].join("\n"),
    );
  }
  return files;
}

export async function checkPublicApi(): Promise<void> {
  for (const [path, expected] of await publicApiFiles()) {
    const actual = await readFile(new URL(`../${path}`, import.meta.url), "utf8");
    if (actual !== expected) throw new Error(`Stale public API bridge: ${path}`);
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  if (process.argv.includes("--check")) await checkPublicApi();
  else
    for (const [path, content] of await publicApiFiles())
      await writeFile(fileURLToPath(new URL(`../${path}`, import.meta.url)), content);
}
